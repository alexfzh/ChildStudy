# ---- 辅助：把 [月龄, P3, P10, P25, P50, P75, P90, P97] 转为 [P3, P15, P50, P85, P97] ----
def _to_five(v7: list[float]) -> list[float]:
    """WS/T 423-2022 标准表给出 7 档 (P3/P10/P25/P50/P75/P90/P97)。
    系统显示按 5 档 (P3/P15/P50/P85/P97)。用线性内插从 P10/P25 推 P15，
    从 P75/P90 推 P85。结果保留 2 位小数。
    """
    p3, p10, p25, p50, p75, p90, p97 = v7
    p15 = round(p10 + 0.5 * (p25 - p10), 2)
    p85 = round(p75 + 0.5 * (p90 - p75), 2)
    return [round(p3, 2), p15, round(p50, 2), p85, round(p97, 2)]


def _interp_months(raw: list[tuple[int, list[float]]], max_month: int) -> dict[int, list[float]]:
    """把稀疏月度采样线性插值到 0..max_month 完整表。
    raw: [(月龄, [P3,P10,P25,P50,P75,P90,P97]), ...]
    """
    raw = sorted(raw, key=lambda x: x[0])
    result: dict[int, list[float]] = {}
    for m in range(max_month + 1):
        # 找左右最近点
        lo_age, lo_v = raw[0]
        hi_age, hi_v = raw[-1]
        for age, v in raw:
            if age <= m:
                lo_age, lo_v = age, v
            if age >= m:
                hi_age, hi_v = age, v
                break
        if lo_age == hi_age:
            result[m] = lo_v
        else:
            t = (m - lo_age) / (hi_age - lo_age)
            result[m] = [round(lo_v[j] + t * (hi_v[j] - lo_v[j]), 2) for j in range(7)]
    return result


