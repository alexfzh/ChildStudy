def _interpolate_table(raw, max_age):
    """From sparse [age_months, p3,p10,p25,p50,p75,p90,p97] to full 0..max_age dict."""
    ages = [r[0] for r in raw]
    result = {}
    for m in range(max_age + 1):
        if m in ages:
            result[m] = raw[ages.index(m)][1:]
        else:
            lo = max(a for a in ages if a <= m)
            hi = min(a for a in ages if a >= m)
            if lo == hi:
                result[m] = raw[ages.index(lo)][1:]
            else:
                i_lo = ages.index(lo)
                i_hi = ages.index(hi)
                t = (m - lo) / (hi - lo)
                result[m] = [
                    round(raw[i_lo][j] + t * (raw[i_hi][j] - raw[i_lo][j]), 2)
                    for j in range(1, 8)
                ]
    return result


def _to_five(result_7):
    """Convert P3/P10/P25/P50/P75/P90/P97 to P3/P15/P50/P85/P97."""
    out = {}
    for m, v in result_7.items():
        p3, p10, p25, p50, p75, p90, p97 = v
        p15 = round(p10 + 0.5 * (p25 - p10), 2)
        p85 = round(p75 + 0.5 * (p90 - p75), 2)
        out[m] = [p3, p15, p50, p85, p97]
    return out


