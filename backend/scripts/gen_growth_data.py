def _dump_dict(d, indent=0):
    pad = "    " * indent
    items = []
    for k, v in d.items():
        if isinstance(v, dict):
            items.append(f"{pad}{k!r}: {{\n{_dump_dict(v, indent+1)}\n{pad}}}")
        else:
            items.append(f"{pad}{k!r}: {v}")
    return ",\n".join(items)


