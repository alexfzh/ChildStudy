async def seed(force: bool = False) -> None:
    await init_db()  # 确保 quotes 表已创建

    # 内容去重（同句只保留一条）
    seen = set()
    unique = []
    for q in QUOTES:
        if q[0] in seen:
            continue
        seen.add(q[0])
        unique.append(q)
    if len(unique) != len(QUOTES):
        print(f"警告：源列表有 {len(QUOTES) - len(unique)} 条重复，已自动去重")

    async with AsyncSessionLocal() as session:
        count = (await session.execute(select(func.count()).select_from(Quote))).scalar_one()
        if count > 0 and not force:
            print(f"quotes 表已有 {count} 条数据，跳过导入（如需重新导入请加 --force）")
            return
        if count > 0 and force:
            # 用原生删除避免逐条 ORM 开销
            from sqlalchemy import delete
            await session.execute(delete(Quote))
            print(f"已清空原有 {count} 条数据")
        for content, author, source, category in unique:
            session.add(
                Quote(content=content, author=author, source=source or None, category=category)
            )
        await session.commit()
        total = (await session.execute(select(func.count()).select_from(Quote))).scalar_one()
        print(f"导入完成，quotes 表共 {total} 条（诗词 {sum(1 for q in unique if q[3]=='poem')} 条 / 名言 {sum(1 for q in unique if q[3]=='quote')} 条）")


if __name__ == "__main__":
    asyncio.run(seed(force="--force" in sys.argv))
